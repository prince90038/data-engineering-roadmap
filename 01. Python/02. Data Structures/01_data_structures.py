# list
l = [1, 2, 3, 4, 5]
print(l[0])  # Output: 1

# tuple
t = tuple([1, 2, 3, 4, 5])
print(t[0])  # Output: 1

# set
s = set([1, 2, 3, 4, 5])
print(s)  # Output: {1, 2, 3, 4, 5}

s = {1, 2, 3, 4, 5}
print(s)  # Output: {1, 2, 3, 4, 5}

# dictionary
d = {'a': 1, 'b': 2, 'c': 3}
print(d['a'])  # Output: 1

